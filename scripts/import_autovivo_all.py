#!/usr/bin/env python3
"""Generate db/seed/003_autovivo_all_parts.sql: every product in the client's public
WooCommerce Store API export (Ferrari, Lamborghini, Maserati), as store-catalogue parts.

Same rules as import_autovivo.py: names, part numbers (SKU), photos and FIT lines are
copied exactly as listed; status is publicly_listed; no prices (all price-on-request);
no assembly links and no vehicle fitment rows beyond those seed 002 already created.
Parts already imported by seed 002 (same SKU) only get brand and FIT lines filled in.
Usage: python3 -I scripts/import_autovivo_all.py products.json > db/seed/003_autovivo_all_parts.sql
"""
import html
import json
import re
import sys

CHECKED = "2026-11-14"
SOURCE = "Autovivo store catalogue (client)"
BRANDS = ("Ferrari", "Lamborghini", "Maserati")


def text(h):
    h = re.sub(r"<(br|/p|/li|/div|/h\d)[^>]*>", "\n", h or "")
    return html.unescape(re.sub(r"<[^>]+>", "", h))


def q(v):
    return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"


def arr(items):
    return "ARRAY[" + ", ".join(q(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


def main(path):
    products = json.load(open(path, encoding="utf-8"))
    out = [
        "-- Generated by scripts/import_autovivo_all.py from the client's public store API.",
        f"-- Snapshot checked {CHECKED}. Do not edit by hand; re-run the script.",
    ]
    seen, n = set(), {b: 0 for b in BRANDS}
    for p in sorted(products, key=lambda x: x["id"]):
        brand = next((c["name"] for c in p["categories"] if c["name"] in BRANDS), None)
        if not brand:
            continue
        name = html.unescape(p["name"]).strip()
        sku = html.unescape(p["sku"]).strip() or None
        if sku and sku in seen:
            continue  # same part number listed twice: keep the first listing
        if sku:
            seen.add(sku)
        t = text(p["short_description"])
        m = re.search(r"FIT\s*:?(.*)", t, re.S | re.I)
        fits = [l.strip() for l in (m.group(1) if m else "").split("\n") if l.strip()][:40]
        desc = re.sub(r"\s+", " ", t.split("FIT")[0]).strip()[:600] or None
        img = next((i["src"] for i in p["images"] if i["src"].startswith("https://")), None)
        scope = ("FIT as listed by the client: " + "; ".join(fits[:12])) if fits else "No FIT list on the client's listing."
        conflict = "ON CONFLICT (oem_part_number) WHERE oem_part_number IS NOT NULL DO NOTHING" if sku else ""
        out.append(
            "INSERT INTO parts (oem_part_number, name, description, listing_url, image_url, brand, fit_models, source_id, source_ref, checked_on, scope_note, verification_status) "
            f"SELECT {q(sku)}, {q(name)}, {q(desc)}, {q(p['permalink'])}, {q(img)}, {q(brand)}, {arr(fits)}, s.id, {q('store product #' + str(p['id']))}, '{CHECKED}', {q(scope)}, 'publicly_listed' "
            f"FROM sources s WHERE s.title = {q(SOURCE)} {conflict};"
        )
        if sku:
            out.append(f"UPDATE parts SET brand = {q(brand)}, fit_models = {arr(fits)} WHERE oem_part_number = {q(sku)} AND brand IS NULL;")
        n[brand] += 1
    sys.stdout.write("\n".join(out) + "\n")
    print(", ".join(f"{b}: {c}" for b, c in n.items()), file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
