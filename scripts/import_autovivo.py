#!/usr/bin/env python3
"""Generate db/seed/002_autovivo_488_gtb.sql from the client's public WooCommerce
Store API export (autovivo.it/wp-json/wc/store/v1/products, all pages, as one JSON list).

Only products whose own FIT list mentions the 488 (GTB or unspecified variant), or
whose title names the 488, are imported. Nothing is inferred:
  * part number   = the store SKU, exactly as listed ("Parts Replaces #")
  * fitment       = one row per FIT line naming the 488 GTB, with the listed market
  * status        = publicly_listed; titles that say 488 while FIT does not are 'disputed'
  * prices        = not imported (all listings are price-on-request)
  * assemblies    = not linked; mapping to the 95 groups needs the client or an EPC.
Usage: python3 -I scripts/import_autovivo.py products.json > db/seed/002_autovivo_488_gtb.sql
"""
import html
import json
import re
import sys

CHECKED = "2026-11-14"
SOURCE = "Autovivo store catalogue (client)"


def text(h):
    h = re.sub(r"<(br|/p|/li|/div|/h\d)[^>]*>", "\n", h or "")
    return html.unescape(re.sub(r"<[^>]+>", "", h))


def q(v):
    return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"


def fits_of(p):
    m = re.search(r"FIT\s*:?(.*)", text(p["short_description"]), re.S | re.I)
    return [l.strip() for l in (m.group(1) if m else "").split("\n") if l.strip()]


def gtb_lines(fits):
    """FIT lines that cover the 488 GTB: '488 GTB (...)' or a bare '488' family line."""
    out = []
    for f in fits:
        u = f.upper()
        if "488" not in u or re.search(r"PISTA|SPIDER|CHALLENGE", u):
            continue
        out.append(f)
    return out


def market(line):
    m = re.search(r"488\s*GTB\s*\(([^)]+)\)", line, re.I)
    return m.group(1).strip().upper() if m else None


def main(path):
    products = json.load(open(path, encoding="utf-8"))
    rows, seen = [], set()
    for p in sorted(products, key=lambda x: x["id"]):
        if not any(c["name"] == "Ferrari" for c in p["categories"]):
            continue
        name = html.unescape(p["name"]).strip()
        sku = html.unescape(p["sku"]).strip() or None
        fits = fits_of(p)
        lines = gtb_lines(fits)
        title_says_488 = re.search(r"\b488", name) is not None
        if not lines and not title_says_488:
            continue
        if sku and sku in seen:
            continue  # same part number listed twice: keep the first listing
        if sku:
            seen.add(sku)
        img = next((i["src"] for i in p["images"] if i["src"].startswith("https://")), None)
        rows.append((p, name, sku, fits, lines, img))

    out = [
        "-- Generated by scripts/import_autovivo.py from the client's public store API.",
        f"-- Snapshot checked {CHECKED}. Do not edit by hand; re-run the script.",
        "INSERT INTO sources (title, publisher, source_type, url, license_notes, access_requirements) VALUES",
        f" ({q(SOURCE)}, 'Autovivo Spare Parts L.L.C', 'client_catalogue', 'https://autovivo.it/',",
        "  'Client''s own product listings, used with the client''s instruction. Part numbers and FIT lists are as listed by the client and not yet checked against an authorized Ferrari catalogue.',",
        "  'Public WooCommerce Store API (robots.txt allows it). No prices imported: all listings are price on request.');",
        "",
    ]
    for p, name, sku, fits, lines, img in rows:
        disputed = not lines
        status = "disputed" if disputed else "publicly_listed"
        scope = ("Title names the 488 but the listing's FIT section lists: " + "; ".join(fits[:8]) + ". Needs client correction."
                 if disputed else "FIT as listed by the client: " + "; ".join(fits[:10]))
        desc = re.sub(r"\s+", " ", text(p["short_description"]).split("FIT")[0]).strip()[:600] or None
        out.append(
            "WITH s AS (SELECT id FROM sources WHERE title=" + q(SOURCE) + "), "
            "p AS (INSERT INTO parts (oem_part_number, name, description, listing_url, image_url, source_id, source_ref, checked_on, scope_note, verification_status) "
            f"SELECT {q(sku)}, {q(name)}, {q(desc)}, {q(p['permalink'])}, {q(img)}, s.id, {q('store product #' + str(p['id']))}, '{CHECKED}', {q(scope)}, '{status}' FROM s RETURNING id)"
        )
        fit_rows = [(market(l), "Listed by the client as: " + l) for l in lines] or [(None, "Disputed: title says 488, FIT list does not.")]
        vals = ", ".join(
            f"((SELECT id FROM p), (SELECT id FROM vehicles WHERE slug='ferrari-488-gtb'), {q(m)}, {q(n + ' VIN not checked.')}, (SELECT id FROM s), {q(p['permalink'])}, '{CHECKED}', '{status}')"
            for m, n in fit_rows
        )
        out.append("INSERT INTO fitments (part_id, vehicle_id, market, notes, source_id, source_ref, checked_on, verification_status) VALUES " + vals + ";")
    out.append("")
    out.append(
        "INSERT INTO data_gaps (vehicle_id, area, missing, access_needed, status, sort_order) VALUES "
        "((SELECT id FROM vehicles WHERE slug='ferrari-488-gtb'), 'Client catalogue mapping', "
        f"'{len(rows)} client-listed 488 parts are not yet linked to assembly groups, quantities or VIN ranges; some listings conflict (title vs FIT).', "
        "'Client confirmation of each part''s assembly group and fitment, ideally checked against Ferrari EPC.', 'open', 90);"
    )
    sys.stdout.write("\n".join(out) + "\n")
    print(f"{len(rows)} parts", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
