#!/usr/bin/env python3
"""Generate db/seed/001_ferrari_488_gtb.sql from the legacy prototype.

The 95 assembly-group titles are read verbatim from legacy/prototype.html so no
value is retyped by hand. Run: python3 scripts/gen_seed.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
html = (ROOT / "legacy" / "prototype.html").read_text()
groups = json.loads(re.search(r"const rawGroups=(\[.*?\]\]);", html, re.S).group(1))
assert len(groups) == 95, len(groups)

# Mirrors categoryFor() in the prototype — a project classification, not OEM data.
SYSTEMS = [
    ("engine-turbo", "Engine & turbo", lambda n: n <= 25),
    ("transmission", "Transmission", lambda n: n <= 29),
    ("chassis-brakes", "Chassis & brakes", lambda n: n <= 44),
    ("electrical-climate", "Electrical & climate", lambda n: n <= 50),
    ("tools-accessories", "Tools & accessories", lambda n: n == 51),
    ("body-exterior", "Body & exterior", lambda n: n <= 119),
    ("cabin-safety", "Cabin & safety", lambda n: n <= 132),
    ("electrical-electronics", "Electrical & electronics", lambda n: n <= 141),
    ("reference", "Reference", lambda n: True),
]


def system_for(code: str) -> str:
    n = int(code)
    for slug, _, test in SYSTEMS:
        if test(n):
            return slug
    raise AssertionError(code)


def q(s):
    return "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"


out = ["-- GENERATED by scripts/gen_seed.py — do not edit by hand.", "BEGIN;", ""]
out.append("""INSERT INTO sources (title, publisher, source_type, url, license_notes, access_requirements) VALUES
 ('Ferrari N.V. prospectus (14 March 2016)', 'Ferrari N.V.', 'manufacturer_publication',
  'https://cdn.ferrari.com/cms/network/media/pdf/ferrari_prospectus_-_final_version_-_14.3.2016.pdf',
  'Public company publication. Model-level facts only; quoted for identification and reference.',
  'Public PDF. Downloaded and re-checked 2026-11-14.'),
 ('Eurospares — Ferrari 488 GTB (USA) part diagrams index', 'Eurospares', 'public_retailer_index',
  'https://www.eurospares.com/ferrari/488/488-gtb-usa/part-diagrams',
  'Third-party retailer page. Not an authorized Ferrari source; no licence to reuse diagrams or part data.',
  'Public page behind a JavaScript bot challenge. Titles captured in prototype commit 83e6d41 (2026-11-13); automated re-check on 2026-11-14 was blocked and NOT bypassed.'),
 ('Ferrari TechInfo', 'Ferrari S.p.A.', 'oem_authorized',
  'https://techinfo.ferrari.com/',
  'Terms of use not yet reviewed. No data from this source is loaded.',
  'Authorized technical-information portal. Registration / subscription and acceptance of terms required — needs owner approval before any sign-up or purchase.'),
 ('Apex Auto Atlas project classification', 'This project', 'project_classification',
  NULL,
  'Grouping of assembly codes into browsable systems, decided by this project. Not Ferrari data.',
  NULL);
""")
out.append("""INSERT INTO vehicles (slug, make, model, market, summary, is_active) VALUES
 ('ferrari-488-gtb', 'Ferrari', '488 GTB', 'USA',
  'Two-seat mid-rear-engined berlinetta. Reference market for the public assembly index is USA. Model year and VIN are not assumed.',
  true);
""")
facts = [
    ("Engine", "3,902 cc turbo V8, mid-rear mounted"),
    ("Power", "670 hp"),
    ("0–200 km/h", "8.3 seconds"),
    ("Launched", "March 2015"),
    ("Body", "Two-seat berlinetta"),
]
rows = []
for i, (label, value) in enumerate(facts):
    rows.append(
        f" ((SELECT id FROM vehicles WHERE slug='ferrari-488-gtb'), {q(label)}, {q(value)}, {i},"
        " (SELECT id FROM sources WHERE source_type='manufacturer_publication'),"
        " 'Prospectus p.47, section \"488 GTB\"', '2026-11-14',"
        " 'Model-level description; may vary by market, model year and configuration.', 'verified')"
    )
out.append("INSERT INTO vehicle_facts (vehicle_id, label, value, sort_order, source_id, source_ref, checked_on, scope_note, verification_status) VALUES\n"
           + ",\n".join(rows) + ";\n")
out.append("INSERT INTO vehicle_systems (slug, name, sort_order, source_id) VALUES\n" + ",\n".join(
    f" ({q(slug)}, {q(name)}, {i}, (SELECT id FROM sources WHERE source_type='project_classification'))"
    for i, (slug, name, _) in enumerate(SYSTEMS)) + ";\n")
rows = []
for code, name in groups:
    rows.append(
        f" ((SELECT id FROM vehicles WHERE slug='ferrari-488-gtb'), (SELECT id FROM vehicle_systems WHERE slug={q(system_for(code))}),"
        f" {q(code)}, {q(name)}, (SELECT id FROM sources WHERE source_type='public_retailer_index'),"
        " 'Group title in public index as captured in prototype commit 83e6d41', '2026-11-13',"
        " 'Ferrari 488 GTB, USA index. Group title only — not a complete parts list; no model-year or VIN scope.', 'publicly_listed')"
    )
out.append("INSERT INTO assemblies (vehicle_id, system_id, code, name, source_id, source_ref, checked_on, scope_note, verification_status) VALUES\n"
           + ",\n".join(rows) + ";\n")
gaps = [
    ("Individual parts", "Individual part names, OEM part numbers, quantities and diagram callouts for each of the 95 groups.",
     "Authorized Ferrari parts catalog access (dealer EPC / TechInfo) or a data licence permitting commercial display."),
    ("Specifications", "Materials, dimensions, torque values, revisions and supersessions.",
     "Authorized Ferrari technical documentation with terms that allow publication."),
    ("Model years", "Which model years the USA index covers.",
     "Authorized catalog or Ferrari documentation stating model-year scope."),
    ("VIN fitment", "VIN ranges / chassis-number breaks per part.",
     "Authorized VIN-decoding catalog access, plus a real VIN to test against."),
    ("3D vehicle model", "A realistic Ferrari 488 GTB 3D model with named meshes per assembly and exploded-view offsets.",
     "A commercially licensed 3D asset (vendor licence reviewed and approved by the owner) or OEM CAD under licence. Not purchased."),
    ("Brand use", "Permission to use Ferrari marks beyond identifying the vehicle.",
     "Legal review; independent-project disclaimer is shown meanwhile."),
    ("Commerce", "Prices, stock, shipping, payment, tax, returns and privacy policy.",
     "Supplier agreement, payment provider account and legal content — none configured."),
]
out.append("INSERT INTO data_gaps (vehicle_id, area, missing, access_needed, sort_order) VALUES\n" + ",\n".join(
    f" ((SELECT id FROM vehicles WHERE slug='ferrari-488-gtb'), {q(a)}, {q(m)}, {q(n)}, {i})"
    for i, (a, m, n) in enumerate(gaps)) + ";\n")
out.append("COMMIT;\n")

dest = ROOT / "db" / "seed" / "001_ferrari_488_gtb.sql"
dest.write_text("\n".join(out))
print(f"wrote {dest} ({len(groups)} assemblies)")
